import assert from "node:assert/strict";
import test from "node:test";
import { readFile, readdir } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { historicalBillRow } from "../src/lib/product/manual-bill-history";
test("manual email journal protects households, replay, cancellation and atomic bill outcomes",async()=>{
 const db=new PGlite();
 const a="11111111-1111-4111-8111-111111111111",b="22222222-2222-4222-8222-222222222222",ha="aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",hb="bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
 const key=(n:number)=>`dddddddd-dddd-4ddd-8ddd-${String(n).padStart(12,"0")}`;
 const record={title:"Synthetic service record",category:"Other",issued_on:"2026-09-01",expires_on:"",notes:"Email reports furnace service; completion not independently confirmed."};
 const begin=async(n:number,hash=String(n).padStart(64,"0"),home=ha)=>(await db.query<{r:{id:string;status:string;run:boolean}}>("select public.begin_rezlee_email_capture($1,$2,$3,$4) r",[home,key(n),hash,key(n+1000)])).rows[0].r;
 const finish=async(n:number,lease=key(n+1000))=>(await db.query<{r:boolean}>("select public.finish_rezlee_email_capture($1,$2,'ready',$3::jsonb) r",[key(n),lease,JSON.stringify({title:record.title,category:"service_invoice"})])).rows[0].r;
 const accept=async(n:number,rec:unknown=record,bill:unknown=null)=>(await db.query<{r:{status:string;documentId:string;billId:string|null}}>("select public.accept_rezlee_email_capture($1,$2,$3::jsonb,$4::jsonb) r",[key(n),ha,JSON.stringify(rec),JSON.stringify(bill)])).rows[0].r;
 try{
  await db.exec(`create role anon;create role authenticated;create role authenticator; create role service_role bypassrls;create schema auth;create schema storage;
   create table auth.users(id uuid primary key,email text);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);alter table storage.objects enable row level security;
   create function storage.foldername(name text) returns text[] language sql immutable as $$select string_to_array(name,'/')$$;
   grant usage on schema public,auth,storage to authenticated,service_role;`);
  for(const file of ["supabase/schema.sql",...(await readdir("supabase/migrations")).filter(f=>f.endsWith(".sql")).sort().map(f=>"supabase/migrations/"+f)])
   await db.exec((await readFile(file,"utf8")).replace(/create extension if not exists "pgcrypto";/g,""));
  await db.exec(`grant select on public.homes,public.documents,public.bills to authenticated;
   insert into auth.users values('${a}','a@example.invalid'),('${b}','b@example.invalid');
   insert into public.homes(id,user_id,nickname) values('${ha}','${a}','A'),('${hb}','${b}','B');
   set role authenticated;set request.jwt.claim.sub='${a}';`);
  await assert.rejects(begin(1,undefined,hb),/Home unavailable/);
  assert.equal((await begin(1)).run,true);assert.equal((await begin(1)).run,false);
  const repeat=await begin(2,String(1).padStart(64,"0"));assert.equal(repeat.id,key(1));assert.equal(repeat.run,false);
  assert.equal(await finish(1,key(9999)),false);assert.equal(await finish(1),true);
  const saved=await accept(1);assert.equal(saved.status,"saved");assert.equal(saved.billId,null);
  assert.deepEqual(await accept(1),saved);
  await assert.rejects(accept(1,{...record,title:"Changed"}),/Save choices changed/);
  await db.exec(`set request.jwt.claim.sub='${b}'`);
  assert.equal((await db.query("select id from public.email_capture_jobs")).rows.length,0);
  assert.equal(await finish(1),false);
  await assert.rejects(accept(1),/Home unavailable/);
  await db.exec(`set request.jwt.claim.sub='${a}'`);
  await begin(3);await db.query("select public.discard_rezlee_email_capture($1)",[key(3)]);
  assert.equal(await finish(3),false);await assert.rejects(accept(3),/Review required/);
  await begin(4);await db.exec("reset role");await db.query("update public.email_capture_jobs set lease_until=now()-interval '1 second' where id=$1",[key(4)]);
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${a}'`);
  assert.equal(await finish(4),false);assert.equal((await begin(4)).run,true);assert.equal(await finish(4),true);
  const bill=historicalBillRow(a,ha,{record_kind:"historical",bill_title:"Synthetic hydro",category:"Electricity",provider_name:"Synthetic hydro",account_number:"QA home",amount:"100.00",billing_period_start:"2026-08-01",billing_period_end:"2026-08-31",due_date:"",issue_date:"2026-09-01"});
  const history=await accept(4,{...record,title:"Hydro email"},bill);assert.ok(history.billId);
  assert.deepEqual(await accept(4,{...record,title:"Hydro email"},bill),history);
  const row=(await db.query<{amount:string;payment_status:null;current_amount_due:null;status:string}>("select amount,payment_status,current_amount_due,status from public.bills where id=$1",[history.billId])).rows[0];
  assert.equal(Number(row.amount),100);assert.equal(row.payment_status,null);assert.equal(row.current_amount_due,null);assert.equal(row.status,"archived");
  await begin(5);await finish(5);
  const before=(await db.query("select id from public.documents")).rows.length;
  await assert.rejects(accept(5,record,{...bill,amount:120,raw_data:{...bill.raw_data,save_signature:"b".repeat(64)}}),/already exists/);
  assert.equal((await db.query("select id from public.documents")).rows.length,before,"no orphan record after duplicate conflict");
  await assert.rejects(accept(5,record,{...bill,currency:"USD"}),/Check statement/);
  await assert.rejects(accept(5,{...record,id:saved.documentId}),/New record/);
  await db.exec("reset role");await db.query("delete from public.documents where id=$1",[saved.documentId]);
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${a}'`);
  assert.equal((await accept(1)).status,"deleted");
  const deletedJournal=(await db.query<{proposal:unknown;accepted_payload:unknown}>("select proposal,accepted_payload from public.email_capture_jobs where id=$1",[key(1)])).rows[0];
  assert.equal(deletedJournal.proposal,null);assert.equal(deletedJournal.accepted_payload,null);
  await db.exec("reset role");
  const deletedReceipt=(await db.query<{payload:{notes:string}}>("select payload from public.vault_save_receipts where request_id=$1",[key(1)])).rows[0];
  assert.equal(deletedReceipt.payload.notes,"");
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${a}'`);
  await assert.rejects(db.exec("update public.email_capture_jobs set status='ready'"),/permission denied/);
  await begin(6);
  await db.query("select public.finish_rezlee_email_capture($1,$2,'failed',null)",[key(6),key(1006)]);
  await begin(7);await begin(8);
  await assert.rejects(begin(9),/Capture limit reached/);
  await assert.rejects(begin(6),/Capture limit reached/,"retry must obey the same live-work cap");
  await finish(7);assert.equal((await begin(6)).run,true);
  await db.exec("reset role");await db.query("delete from auth.users where id=$1",[a]);
  assert.equal((await db.query("select id from public.email_capture_jobs")).rows.length,0);
 }finally{await db.close();}
});
